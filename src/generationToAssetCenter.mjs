/**
 * Convert a batch of approved generation outputs to Asset Center catalog entries
 * This is called after the review board approves outputs
 */
function batchOutputsToCatalogEntries(batchJobs, approvedJobIds = []) {
  const entries = []
  for (const job of batchJobs) {
    if (!approvedJobIds.includes(job.jobId) && !job.outputAssetId) continue
    if (job.status !== 'approved' && job.status !== 'completed') continue

    // The outputAssetId should contain the provider result
    const output = job.outputAssetId
    if (!output) continue

    try {
      // The outputAssetId might be a path, URL, or structured object
      let outputData = output
      if (typeof output === 'string') {
        // Try to parse if it's JSON
        try {
          outputData = JSON.parse(output)
        } catch {
          // It's a plain path/URL
          outputData = { downloadUrl: output, providerTaskId: job.providerTaskId }
        }
      }

      const entry = generationOutputToCatalogEntry(outputData)
      entries.push({
        jobId: job.jobId,
        entry,
        metadata: {
          sceneIndex: job.sceneIndex,
          sceneRole: job.normalizedRequest?.sceneRole,
          durationSec: job.normalizedRequest?.durationSec
        }
      })
    } catch (e) {
      console.warn(`Failed to convert job ${job.jobId} to catalog entry:`, e.message)
    }
  }
  return entries
}

/**
 * Install a generation output into the Asset Center (trigger download + register)
 * This is the bridge between generation completion and Asset Center availability
 */
async function installGenerationToAssetCenter(assetCenter, job, downloadDir) {
  // job should have: outputAssetId, providerTaskId, providerId, model, etc.
  if (!job.outputAssetId) throw new Error('Job has no outputAssetId')

  let outputData = job.outputAssetId
  if (typeof outputData === 'string') {
    try {
      outputData = JSON.parse(outputData)
    } catch {
      outputData = { downloadUrl: outputData, providerTaskId: job.providerTaskId }
    }
  }

  const entry = generationOutputToCatalogEntry(outputData)

  // Register in catalog
  await assetCenter.registerCatalogEntry(entry)

  // If remote, queue download
  if (entry.source?.type === 'remote' && entry.source.url) {
    await assetCenter.downloadPackage(entry.id, { destDir, onProgress: null })
  }

  return entry.id
}

/**
 * Filter Asset Center entries suitable for assembly (music beds, SFX, title presets)
 */
function getAssemblyReadyAssets(catalog, roles = ['music', 'sfx']) {
  return catalog.filter(entry => {
    if (!entry.assetKind === 'media') return false
    if (entry.category === 'music' && roles.includes('music')) return true
    if (entry.category === 'sound-effects' && roles.includes('sfx')) return true
    if (entry.assetKind === 'title-preset' && roles.includes('title')) return true
    if (entry.assetKind === 'effect-preset' && roles.includes('effect')) return true
    return false
  }).map(entry => ({
    entryId: entry.id,
    title: entry.title,
    category: entry.category,
    assetKind: entry.assetKind,
    durationSec: entry.generationMeta?.durationSec || 0,
    fileSizeBytes: entry.sizeBytes,
    license: entry.license,
    source: entry.source,
    previewRef: entry.previewRef
  }))
}

